    private void popuniPolja() {
       try {
        Properties properties = new Properties();
        properties.load(new FileInputStream("dbconfig.properties"));
        String url = properties.getProperty("url");
        txtNazivBaze.setText(url.substring(url.lastIndexOf("/") + 1));
        txtUsername.setText(properties.getProperty("username"));
        txtPassword.setText(properties.getProperty("password"));
    } catch (IOException ex) {
        Logger.getLogger(KonfiguracijaBaze.class.getName()).log(Level.SEVERE, null, ex);
    }
    }
