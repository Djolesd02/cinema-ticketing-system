    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        try {
            if (txtEmail.getText().isEmpty() || txtTelefon.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
            m.setEmail(txtEmail.getText());
            m.setKontaktTelefon(txtTelefon.getText());
            m.setStarosnoDoba((StarosnoDoba) cmbStarosnoDoba.getSelectedItem());
            ClientController.getInstance().updateMusterija(m);
            ((FormPretragaMusterije) getParent()).refreshTable();
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio musteriju.");
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti musteriju");
        }
    }//GEN-LAST:event_btnIzmeniActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Obrisati ovu musteriju?", "Konfirmacija", JOptionPane.YES_NO_OPTION);
        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteMusterija(m);
                ((FormPretragaMusterije) getParent()).refreshTable();
                JOptionPane.showMessageDialog(this, "Sistem je obrisao musteriju.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da obrise musteriju");
            }
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

    /**
     * @param args the command line arguments
     */
    
    private void popuniStarosnoDoba() {
        try {
            ArrayList<StarosnoDoba> lista = ClientController.getInstance().getAllStarosnoDoba();
            cmbStarosnoDoba.removeAllItems();
            for (StarosnoDoba sd : lista) {
                cmbStarosnoDoba.addItem(sd);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormNovaMusterija.class.getName()).log(Level.SEVERE, null, ex);
        }
}
