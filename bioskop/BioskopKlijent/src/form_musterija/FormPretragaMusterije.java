   private void popuniStarosnoDoba() {
    try {
        cmbStarosnoDoba.removeAllItems();
        cmbStarosnoDoba.addItem(null); // prazno = ne filtriraj po starosnom dobu
        for (StarosnoDoba sd : ClientController.getInstance().getAllStarosnoDoba()) {
            cmbStarosnoDoba.addItem(sd);
        }
    } catch (Exception ex) {
        Logger.getLogger(FormPretragaMusterije.class.getName()).log(Level.SEVERE, null, ex);
    }
}

private void pretrazi(boolean prikaziPoruku) {
    try {
        Musterija kriterijum = new Musterija();
        kriterijum.setImePrezime(txtPretraga.getText());
        kriterijum.setStarosnoDoba((StarosnoDoba) cmbStarosnoDoba.getSelectedItem());

        ArrayList<Musterija> lista = ClientController.getInstance().pretraziMusterija(kriterijum);
        ((TableModelMusterije) tblMusterije.getModel()).postaviListu(lista);

        if (prikaziPoruku) {
            if (lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje musterije po zadatim kriterijumima");
            } else {
                JOptionPane.showMessageDialog(this, "Sistem je nasao musterije po zadatim kriterijumima");
            }
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje musterije po zadatim kriterijumima");
    }
}

   
