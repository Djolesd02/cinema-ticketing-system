    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed
        try {
            if (txtIme.getText().isEmpty() || txtPrezime.getText().isEmpty()
                    || txtEmail.getText().isEmpty() || txtTelefon.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
            Musterija m = new Musterija(null,
                    txtIme.getText(), txtPrezime.getText(),
                    txtIme.getText() + " " + txtPrezime.getText(),
                    txtEmail.getText(), txtTelefon.getText(),
                    (StarosnoDoba) cmbStarosnoDoba.getSelectedItem());
            ClientController.getInstance().addMusterija(m);
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio musteriju.");
            Session.getInstance().getMf().popuniMusterije();
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti musteriju");
        }
    }//GEN-LAST:event_btnDodajActionPerformed

    /**
     * @param args the command line arguments
     */
 
    private void popuniStarosnoDoba() {
        try {
            ArrayList<StarosnoDoba> lista = ClientController.getInstance().getAllStarosnoDoba();
            cmbStarosnoDoba.removeAllItems();
            for (StarosnoDoba sd : lista) {
                cmbStarosnoDoba.addItem(sd);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormNovaMusterija.class.getName()).log(Level.SEVERE, null, ex);
        }
}
