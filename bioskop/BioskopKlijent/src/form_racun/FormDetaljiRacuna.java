    private void btnStornirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStornirajActionPerformed
       int result = JOptionPane.showConfirmDialog(this, "Stornirati ovaj racun?", "Potvrda", JOptionPane.YES_NO_OPTION);
        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().cancelRacun(r);
                ((FormPretragaRacuna) getParent()).refreshTable();
                JOptionPane.showMessageDialog(this, "Sistem je stornirao racun.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da stornira racun");
            }
        }
    }//GEN-LAST:event_btnStornirajActionPerformed

