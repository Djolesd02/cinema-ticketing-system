    private void popuniMusterije() {
        try {
            cmbMusterija.removeAllItems();
            for (Musterija m : ClientController.getInstance().getAllMusterija()) {
                cmbMusterija.addItem(m);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormIzmenaRacuna.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    private void popuniProjekcije() {
        try {
            cmbProjekcija.removeAllItems();
            for (Projekcija p : ClientController.getInstance().getAllProjekcija()) {
                cmbProjekcija.addItem(p);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormIzmenaRacuna.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
