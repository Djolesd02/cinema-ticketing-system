    private void btnIzracunajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzracunajActionPerformed
        if (txtKolicina.getText().isEmpty()) {
            return;
        }
        Projekcija p = (Projekcija) cmbProjekcija.getSelectedItem();
        int kolicina = Integer.parseInt(txtKolicina.getText());
        if (kolicina <= 0) {
            JOptionPane.showMessageDialog(this, "Kolicina mora biti veca od 0!");
            return;
        }
        txtIznos.setText(String.valueOf(p.getCena() * kolicina));
    }//GEN-LAST:event_btnIzracunajActionPerformed

    private void btnObrisiStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiStavkuActionPerformed
        int row = tblStavke.getSelectedRow();
        if (row >= 0) {
            TableModelStavkeRacuna tm = (TableModelStavkeRacuna) tblStavke.getModel();
            tm.obrisiStavku(row);
            ukupanIznos = tm.vratiUkupanIznos();
            txtUkupanIznos.setText(String.valueOf(ukupanIznos));
        }
    }//GEN-LAST:event_btnObrisiStavkuActionPerformed

    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed
        if (txtIznos.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Morate izracunati iznos!");
            return;
        }
        Projekcija p = (Projekcija) cmbProjekcija.getSelectedItem();
        int kolicina = Integer.parseInt(txtKolicina.getText());
        double iznos = Double.parseDouble(txtIznos.getText());

        StavkaRacuna sr = new StavkaRacuna(null, -1, kolicina, iznos, p);
        TableModelStavkeRacuna tm = (TableModelStavkeRacuna) tblStavke.getModel();
        tm.dodajStavku(sr);
        ukupanIznos = tm.vratiUkupanIznos();
        txtUkupanIznos.setText(String.valueOf(ukupanIznos));
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

    private void btnSacuvajRacunActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajRacunActionPerformed
        try {
            TableModelStavkeRacuna tm = (TableModelStavkeRacuna) tblStavke.getModel();
            if (tm.getLista().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Racun mora imati barem jednu stavku!");
                return;
            }
        r.setMusterija((Musterija) cmbMusterija.getSelectedItem());
        r.setUkupnaCena(ukupanIznos);
        r.setDatumVreme(new Date());
        r.setStavkeRacuna(tm.getLista());
        ClientController.getInstance().updateRacun(r);
        ((FormPretragaRacuna) getParent()).refreshTable();
        JOptionPane.showMessageDialog(this, "Sistem je zapamtio racun.");
        this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti racun");
        }
    }//GEN-LAST:event_btnSacuvajRacunActionPerformed

