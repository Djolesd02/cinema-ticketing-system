    void refreshTable() {
       pretrazi(false);
    }
    private void pretrazi(boolean prikaziPoruku) {
        try {
            Racun kriterijum = new Racun();
            Musterija m = new Musterija();
            m.setImePrezime(txtPretraga.getText());
            kriterijum.setMusterija(m);

            ArrayList<Racun> lista = ClientController.getInstance().pretraziRacun(kriterijum);
            ((TableModelRacuni) tblRacuni.getModel()).postaviListu(lista);

            if (prikaziPoruku) {
                if (lista.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje racune po zadatim kriterijumima");
                } else {
                    JOptionPane.showMessageDialog(this, "Sistem je nasao racune po zadatim kriterijumima");
                }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje racune po zadatim kriterijumima");
        }
    }

