    private void btnPrijavaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrijavaActionPerformed
       String korisnickoIme = txtKorisnickoIme.getText();
       String sifra = String.valueOf(txtSifra.getPassword());

        Kasir kasir = new Kasir();
        kasir.setKorisnickoIme(korisnickoIme);
        kasir.setSifra(sifra);

        try {
            Kasir ulogovani = ClientController.getInstance().login(kasir);
            if (ulogovani != null) {
                Session.getInstance().setUlogovani(ulogovani);
                JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra su ispravni.");
                new MainForm().setVisible(true);
                this.dispose();
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra nisu ispravni");
}
    }//GEN-LAST:event_btnPrijavaActionPerformed

