    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed
        try {
            if (txtNazivFilma.getText().isEmpty() || txtCena.getText().isEmpty()
                    || txtZanr.getText().isEmpty() || txtTrajanje.getText().isEmpty()
                    || txtDatumVreme.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
            Projekcija p = new Projekcija(null,
                    txtNazivFilma.getText(),
                    Double.parseDouble(txtCena.getText()),
                    (String) cmbTipProjekcije.getSelectedItem(),
                    txtZanr.getText(),
                    Integer.parseInt(txtTrajanje.getText()),
                    new SimpleDateFormat("dd.MM.yyyy HH:mm").parse(txtDatumVreme.getText()));
            ClientController.getInstance().addProjekcija(p);
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio projekciju.");
            Session.getInstance().getMf().popuniProjekcije();
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti projekciju");
        }
    }//GEN-LAST:event_btnDodajActionPerformed

