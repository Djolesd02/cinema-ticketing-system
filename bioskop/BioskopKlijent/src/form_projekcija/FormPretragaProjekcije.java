    /**
     * @param args the command line arguments
     */
    void refreshTable() {
        pretrazi(false);
    }
    
    private void pretrazi(boolean prikaziPoruku) {
    try {
        Projekcija kriterijum = new Projekcija();
        kriterijum.setNazivFilma(txtPretraga.getText());

        ArrayList<Projekcija> lista = ClientController.getInstance().pretraziProjekcija(kriterijum);
        ((TableModelProjekcije) tblProjekcije.getModel()).postaviListu(lista);

        if (prikaziPoruku) {
            if (lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje projekcije po zadatim kriterijumima");
            } else {
                JOptionPane.showMessageDialog(this, "Sistem je nasao projekcije po zadatim kriterijumima");
            }
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje projekcije po zadatim kriterijumima");
    }
}
 
