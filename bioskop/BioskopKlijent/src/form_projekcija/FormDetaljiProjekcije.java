    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Obrisati ovu projekciju?", "Konfirmacija", JOptionPane.YES_NO_OPTION);
        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteProjekcija(p);
                ((FormPretragaProjekcije) getParent()).refreshTable();
                JOptionPane.showMessageDialog(this, "Sistem je obrisao projekciju.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da obrise projekciju");
            }
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        try {
            p.setCena(Double.parseDouble(txtCena.getText()));
            p.setTipProjekcije((String) cmbTipProjekcije.getSelectedItem());
            p.setZanr(txtZanr.getText());
            p.setTrajanje(Integer.parseInt(txtTrajanje.getText()));
            p.setDatumVreme(new SimpleDateFormat("dd.MM.yyyy HH:mm").parse(txtDatumVreme.getText()));
            ClientController.getInstance().updateProjekcija(p);
            ((FormPretragaProjekcije) getParent()).refreshTable();
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio projekciju.");
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti projekciju");
        }
    }//GEN-LAST:event_btnIzmeniActionPerformed

